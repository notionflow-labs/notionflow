const $ = id => document.getElementById(id);
const appHost = location.hostname === 'app.notionflow.app';
const api = appHost ? 'https://api.notionflow.app' : '';
if (appHost) { $('home-link').href = 'https://notionflow.app/'; document.querySelectorAll('[data-site-link]').forEach(a => { a.href = `https://notionflow.app${a.getAttribute('href')}`; }); }
let mode = 'sample', sample, receipt, pdf = null, busy = false, published = false, available = { live:false,notion:false };
function message(id,text,error=false) { const el = $(id); el.hidden = !text; el.className = `message${error ? ' error' : ''}`; el.textContent = text; }
async function request(path,data) {
  const headers = {}; if (data) headers['content-type'] = 'application/json';
  if ($('access').value) headers.authorization = `Bearer ${$('access').value}`;
  const response = await fetch(api+path,{ method:data ? 'POST':'GET',headers,...(data ? { body:JSON.stringify(data) }:{}),signal:AbortSignal.timeout(70000) });
  let result; try { result = await response.json(); } catch { throw new Error('The server returned an unreadable response.'); }
  if (!response.ok) throw new Error(result.error || `Request failed (${response.status}).`);
  return result;
}
function updateButtons() {
  $('generate').disabled = busy || (mode === 'live' && !available.live);
  $('generate').textContent = busy ? 'Working…' : mode === 'sample' ? 'Open saved draft ↗' : 'Create draft with Claude ↗';
  $('sample-mode').disabled = $('live-mode').disabled = $('kind').disabled = busy;
  $('source').readOnly = mode === 'sample' || Boolean(pdf) || busy;
  $('file').disabled = busy;
  $('import-notion').disabled = busy || !available.notion;
  $('publish').disabled = busy || !available.notion || mode !== 'live' || !$('confirm-publish').checked || published;
  document.querySelectorAll('#report textarea, #report input, #report .secondary').forEach(el => { el.disabled = busy || (published && el.matches('textarea,input')); });
}
function node(tag,text,className) { const el = document.createElement(tag); if (text !== undefined) el.textContent = text; if (className) el.className = className; return el; }
function sampleView() {
  const value = structuredClone(sample); value.kind = $('kind').value;
  if (value.kind === 'brief') { value.report.title = 'Harbor Studio · website project brief'; value.report.summary = 'First release: homepage, service pages and contact form, with launch agreed for November 6, 2026. The customer portal is outside scope. Analytics requirements and ongoing maintenance remain unresolved.'; }
  if (value.kind === 'tasks') { value.report.title = 'Harbor Studio · action items'; value.report.summary = 'Three action items were identified: approved copy, mobile form testing and analytics requirements. Two have explicit owners and due dates. Analytics remains unassigned with no agreed deadline.'; }
  return value;
}
function render(value) {
  receipt = structuredClone(value); published = false; $('confirm-publish').checked = false;
  const r = receipt.report;
  $('empty').hidden = true; $('report').hidden = false;
  $('draft-title').value = r.title; $('draft-summary').value = r.summary;
  $('draft-badge').textContent = receipt.mode === 'sample' ? 'SAVED EXAMPLE' : 'CLAUDE DRAFT';
  $('decisions').replaceChildren(); $('tasks').replaceChildren();
  if (!r.decisions.length) $('decisions').append(node('p','No decisions were extracted.','input-note'));
  r.decisions.forEach((d,i) => {
    const input = node('textarea',undefined,'editable-decision'); input.value=d.text; input.maxLength=1500; input.dataset.index=i; input.setAttribute('aria-label',`Decision ${i+1}`);
    $('decisions').append(input,node('p',`“${d.evidence}”`,'evidence'));
  });
  if (!r.tasks.length) $('tasks').append(node('p','No concrete tasks were extracted.','input-note'));
  r.tasks.forEach((t,i) => {
    const card = node('div',undefined,'task-editor');
    const title = node('input'); title.value=t.title; title.maxLength=300; title.dataset.field='title'; title.setAttribute('aria-label',`Task ${i+1}`); card.append(title);
    const meta = node('div',undefined,'task-meta');
    for (const [field,label] of [['owner','Owner'],['due','Due date']]) { const wrap=node('label',label), input=node('input'); input.type=field==='due' ? 'date':'text'; input.maxLength=field==='due' ? 10:100; input.value=t[field]; input.dataset.field=field; input.placeholder='Unassigned'; wrap.append(input); meta.append(wrap); }
    card.append(meta,node('p',`“${t.evidence}”`,'evidence')); $('tasks').append(card);
  });
  $('questions').value = r.questions.join('\n');
  $('report-info').textContent = receipt.mode === 'sample' ? 'This is a saved example. Edit or download it; opening it does not call Claude.' : `Generated by ${receipt.model}. ${receipt.evidenceCheck === 'text-match' ? 'Excerpts were checked against your text. Review the draft for mistakes.' : 'Compare PDF excerpts against the original file.'} ${receipt.usage ? `Input: ${receipt.usage.input_tokens ?? 0} tokens · Output: ${receipt.usage.output_tokens ?? 0} tokens.` : ''}`;
  message('output-message',receipt.warnings?.join(' ') || ''); updateButtons();
}
function currentReport() {
  if (!receipt) throw new Error('Create a draft first.');
  const result = structuredClone(receipt.report);
  result.title=$('draft-title').value.trim(); result.summary=$('draft-summary').value.trim();
  result.decisions.forEach((d,i) => { d.text = $('decisions').querySelectorAll('textarea')[i].value.trim(); });
  result.tasks.forEach((t,i) => { const card=$('tasks').children[i]; ['title','owner','due'].forEach(f => { t[f]=card.querySelector(`[data-field="${f}"]`).value.trim(); }); });
  result.questions=$('questions').value.split('\n').map(s => s.trim()).filter(Boolean);
  if (!result.title) throw new Error('Give the page a title before exporting.');
  if (result.questions.length>15) throw new Error('Keep at most 15 open questions.');
  return result;
}
function markdown(r) { return `# ${r.title}\n\n${r.summary}\n\n## Decisions\n\n${r.decisions.map(d => `- ${d.text}\n  > ${d.evidence}`).join('\n')}\n\n## Tasks\n\n${r.tasks.map(t => `- [ ] ${t.title} — ${t.owner || 'Unassigned'}${t.due ? ` · ${t.due}` : ''}\n  > ${t.evidence}`).join('\n')}\n\n## Open questions\n\n${r.questions.map(q => `- ${q}`).join('\n')}\n`; }
function download(type) {
  try {
    const report=currentReport(), value=type==='md' ? markdown(report) : JSON.stringify({ ...receipt,report,userEdited:JSON.stringify(report)!==JSON.stringify(receipt.report),exportedAt:new Date().toISOString() },null,2);
    const url=URL.createObjectURL(new Blob([value],{ type:type==='md' ? 'text/markdown;charset=utf-8':'application/json' }));
    const a=document.createElement('a'); a.href=url; a.download=`notionflow-${report.title.toLowerCase().replace(/[^a-z0-9]+/g,'-').slice(0,60)||'document'}.${type}`; document.body.append(a); a.click(); a.remove(); setTimeout(() => URL.revokeObjectURL(url),10000);
    message('output-message','Your export includes the current edited draft.');
  } catch(e) { message('output-message',e.message,true); }
}
function selectMode(next) {
  if (busy) return;
  mode=next; pdf=null; receipt=null; published=false; $('file').value=''; $('file-info').textContent='';
  $('sample-mode').setAttribute('aria-pressed',String(mode==='sample')); $('live-mode').setAttribute('aria-pressed',String(mode==='live'));
  $('sample-note').hidden=mode!=='sample'; $('live-controls').hidden=mode!=='live';
  $('source').value=mode==='sample' ? sample?.source || '' : '';
  $('source').placeholder='Paste meeting notes, a project document or the text you want to organize…';
  $('empty').hidden=false; $('report').hidden=true; message('input-message',''); message('output-message',''); updateSize(); updateButtons();
  if (mode==='live' && !available.live) message('input-message','Live processing is not configured on this preview. You can inspect and export the saved example.');
}
function updateSize() { $('source-size').textContent = `${$('source').value.length.toLocaleString()} characters${mode==='sample' ? ' · fixed source' : ' · 30,000 maximum'}`; }
$('sample-mode').addEventListener('click',() => selectMode('sample'));
$('live-mode').addEventListener('click',() => selectMode('live'));
$('source').addEventListener('input',updateSize);
$('file').addEventListener('change',async () => {
  const file=$('file').files[0]; pdf=null; updateButtons(); if (!file) return;
  try {
    if (/\.pdf$/i.test(file.name)) {
      if(file.size>1048576) throw new Error('Choose a PDF of at most 1 MB.');
      const bytes=new Uint8Array(await file.arrayBuffer()); if(new TextDecoder().decode(bytes.slice(0,5))!=='%PDF-') throw new Error('This file does not have a PDF header.');
      let binary=''; for(let i=0;i<bytes.length;i+=16384) binary+=String.fromCharCode(...bytes.subarray(i,i+16384)); pdf=btoa(binary);
      $('source').value=''; $('file-info').textContent=`${file.name} · PDF selected. Claude will read this file when you create a draft.`;
    } else {
      if(!/\.(txt|md|markdown)$/i.test(file.name) || file.size>120000) throw new Error('Choose TXT/Markdown up to 30,000 characters, or a PDF up to 1 MB.');
      const text=await file.text(); if(text.length>30000) throw new Error('This text exceeds 30,000 characters.');
      $('source').value=text; $('file-info').textContent=file.name;
    }
    message('input-message',''); updateSize(); updateButtons();
  } catch(e) { $('file').value=''; $('file-info').textContent=''; message('input-message',e.message,true); }
});
$('generate').addEventListener('click',async () => {
  if(mode==='sample') { if(sample) render(sampleView()); return; }
  if(!$('access').value.trim()) { message('input-message','Enter your preview access code.',true); return; }
  busy=true; updateButtons(); message('input-message','Creating a draft. Nothing is being written to Notion.');
  try { render(await request('/api/generate',{ kind:$('kind').value,...(pdf ? { pdf } : { text:$('source').value }) })); message('input-message','Draft ready. Review the output and source excerpts.'); }
  catch(e) { message('input-message',e.name==='TimeoutError' ? 'The request timed out. No draft was received; check usage before retrying.' : e.message,true); }
  finally { busy=false; updateButtons(); }
});
$('kind').addEventListener('change',() => { if(mode==='sample' && receipt) render(sampleView()); });
$('import-notion').addEventListener('click',async () => {
  busy=true; updateButtons(); message('input-message','Reading the selected Notion page…');
  try { const result=await request('/api/notion/read',{ pageId:$('notion-page').value.trim() }); pdf=null; $('file').value=''; $('file-info').textContent=''; $('source').value=result.text; updateSize(); message('input-message',`Imported ${result.title}.${result.truncated ? ' Some blocks were omitted or the read limit was reached. Review the imported text.' : ''}`); }
  catch(e) { message('input-message',e.message,true); } finally { busy=false; updateButtons(); }
});
$('confirm-publish').addEventListener('change',updateButtons);
$('publish').addEventListener('click',async () => {
  try {
    const report=currentReport(); busy=true; updateButtons(); message('output-message','Creating a new page in the configured Notion destination…');
    const result=await request('/api/notion/publish',{ report,confirm:$('confirm-publish').checked,createDatabase:$('create-db').checked });
    published=true; message('output-message',result.warning || `Notion page created. ${result.tasksCreated} task database entries created.`);
    if(result.pageUrl && /^https:\/\/(?:(?:www|app)\.)?notion\.(?:so|com)\//.test(result.pageUrl)) { const a=node('a',' Open the page ↗'); a.href=result.pageUrl; a.target='_blank'; a.rel='noopener noreferrer'; $('output-message').append(a); }
  } catch(e) { message('output-message',`${e.message} Check the Notion destination before retrying; a page may have been created.`,true); }
  finally { busy=false; updateButtons(); }
});
$('export-md').addEventListener('click',() => download('md'));
$('export-json').addEventListener('click',() => download('json'));
$('copy').addEventListener('click',async () => { try { await navigator.clipboard.writeText(markdown(currentReport())); message('output-message','Markdown copied.'); } catch { message('output-message','Clipboard access was unavailable. Download Markdown instead.',true); } });
async function init() {
  const results=await Promise.allSettled([request('/api/sample'),request('/api/status')]);
  if(results[0].status==='fulfilled') { sample=results[0].value; $('source').value=sample.source; updateSize(); }
  else message('input-message','The saved example could not be loaded. Reload the page.',true);
  if(results[1].status==='fulfilled') available=results[1].value;
  $('service-status').textContent=available.live ? 'Claude available · access code required' : 'Sample available · live processing unavailable';
  $('notion-status').textContent=available.notion ? 'This saves the draft in our demo workspace, where we can see it. Use sample or non-sensitive notes. Opening the result in Notion requires permission. To save your own draft, select Your document and enter your access code.' : 'Notion is not connected. You can still download the draft.';
  updateButtons();
}
init();
